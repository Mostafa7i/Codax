// ─────────────────────────────────────────────────────────────────────────────
// 📊 أوزان المعادلة الإجمالية (Combined Score)
// يجب أن يكون مجموعهما 1.0 (أي 100%)
// ─────────────────────────────────────────────────────────────────────────────
export const TASK_WEIGHT        = 0.6;   // وزن التاسكات في المعادلة النهائية (60%)
export const ATTENDANCE_WEIGHT  = 0.4;   // وزن الحضور في المعادلة النهائية  (40%)

// ─────────────────────────────────────────────────────────────────────────────
// ⚡ نظام البوست (النقاط الإضافية → رفع نسبة المتوسط)
//
//  كيف يعمل؟
//    كل BOOST_POINTS_PER_PERCENT نقطة إضافية = +1% في المتوسط النهائي
//    مثال الإعداد الحالي:
//      40 نقطة = +1%
//      80 نقطة = +2%
//      ...
//      200 نقطة = +5% (الحد الأقصى)
//
//  لو أردت 1% كل 50 نقطة:
//    غيّر BOOST_POINTS_PER_PERCENT = 50
//
//  لو أردت حد أقصى 10% بدلاً من 5%:
//    غيّر BOOST_MAX_PERCENT = 10
// ─────────────────────────────────────────────────────────────────────────────
export const BOOST_POINTS_PER_PERCENT = 60;  // كم نقطة إضافية تساوي 1% بوست
export const BOOST_MAX_PERCENT        = 5;   // الحد الأقصى للبوست (بالنسبة المئوية)

// ─────────────────────────────────────────────────────────────────────────────
// 🔢 النقاط الكاملة لبلوغ أقصى بوست (مشتقة تلقائياً — لا تعدّلها يدوياً)
// = BOOST_POINTS_PER_PERCENT × BOOST_MAX_PERCENT
// مثال: 40 × 5 = 200 نقطة
// ─────────────────────────────────────────────────────────────────────────────
export const BOOST_MAX_POINTS = BOOST_POINTS_PER_PERCENT * BOOST_MAX_PERCENT;

// ─────────────────────────────────────────────────────────────────────────────
// 🎯 الهدف الأقصى لمقياس النقاط (الدائرة البيانية في البروفايل)
// مشتق تلقائياً من النقاط المطلوبة لبلوغ أقصى بوست.
// عندما يحصل الطالب على أقصى بوست تكتمل الدائرة 100%.
// ─────────────────────────────────────────────────────────────────────────────
export const POINTS_TARGET_DISPLAY = BOOST_MAX_POINTS;

// ─────────────────────────────────────────────────────────────────────────────
// 🎓 مستويات ترقية المعادل (Upgrade Tiers) — تُولَّد تلقائياً
// كل مستوى: { minPoints: الحد الأدنى, boostValue: قيمة البوست %, label: "+X%" }
// ─────────────────────────────────────────────────────────────────────────────
export const BOOST_TIERS = Array.from(
  { length: BOOST_MAX_PERCENT },
  (_, i) => ({
    minPoints : (i + 1) * BOOST_POINTS_PER_PERCENT,
    boostValue: i + 1,
    label     : `+${i + 1}%`,
  })
);

// ─────────────────────────────────────────────────────────────────────────────
// 🧮 دوال مساعدة موحدة لحساب البوست (تُستخدم عبر المنصة بالكامل)
// ─────────────────────────────────────────────────────────────────────────────

/**
 * حساب قيمة نسبة البوست المئوية من رصيد النقاط
 * @param {number} points - رصيد النقاط الإضافية
 * @returns {number} قيمة البوست الصحيحة (من 0 إلى BOOST_MAX_PERCENT)
 */
export const calculateBoostPercentage = (points = 0) => {
  const safePoints =
    typeof points === "number" && !isNaN(points) ? Math.max(0, points) : 0;
  return Math.min(
    Math.floor(safePoints / BOOST_POINTS_PER_PERCENT),
    BOOST_MAX_PERCENT,
  );
};

/**
 * نص شارة البوست للعرض في الكروت والبروفايل (مثال: "+5%" أو "+1%")
 * @param {number} points - رصيد النقاط الإضافية
 * @returns {string|null} نص البوست أو null إذا لم يكن هناك بوست
 */
export const getBoostBadgeText = (points = 0) => {
  const boost = calculateBoostPercentage(points);
  return boost > 0 ? `+${boost}%` : null;
};

